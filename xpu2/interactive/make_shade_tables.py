"""Writes shade_tables.h: MoonRay's precomputed shading tables as shared CPU/CUDA arrays.

make_shade_tables.py --source <MoonRay for Modo checkout> [--output shade_tables.h]

The tables are read from the OpenMoonRay sources the checkout carries (Apache-2.0, DreamWorks Animation; see
MOONRAY_LICENSE.txt), never retyped: the microfacet energy-compensation albedos, the velvet albedos, and the fabric
and velvet normalisation factors. Each array keeps its MoonRay name with the module prefix as a namespace."""
import argparse
import re
from pathlib import Path

SHADING = 'upstream/openmoonray/moonray/moonray/lib/rendering/shading/ispc/bsdf'
TABLES = [
    ('cook_torrance/energy_conservation/ReflectionAlbedo.inl',
     ['ReflectionAlbedo_BeckmannE', 'ReflectionAlbedo_GGXE', 'ReflectionAlbedo_BeckmannOneMinusEavg',
      'ReflectionAlbedo_GGXOneMinusEavg']),
    ('cook_torrance/energy_conservation/TransmissionAlbedo.inl',
     ['TransmissionAlbedo_E', 'TransmissionAlbedo_EExit', 'TransmissionAlbedo_OneMinusEavg',
      'TransmissionAlbedo_OneMinusEavgExit']),
    ('fabric/VelvetAlbedoTable.isph', ['VelvetAlbedo_avgAlbedo', 'VelvetAlbedo_albedoTable']),
    ('fabric/BsdfFabric.isph', ['precomputedDwaFabricNormalizationFactor']),
    ('fabric/BsdfFabricVelvet.ispc', ['BsdfFabricVelvet_precomputedNormalizationTable']),
]
NUMBER = re.compile(r'[-+]?(?:\d+\.\d*|\.\d+|\d+)(?:[eE][-+]?\d+)?f?')


def extract(text, name):
    m = re.search(r'\b' + re.escape(name) + r'\s*\[[^\]]*\]\s*=\s*\{', text)
    if not m:
        raise SystemExit('Table not found: ' + name)
    end = text.index('}', m.end())
    body = re.sub(r'//[^\n]*', '', text[m.end():end])
    values = [v.rstrip('f') for v in NUMBER.findall(body)]
    if not values:
        raise SystemExit('Empty table: ' + name)
    return values


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source', type=Path, required=True)
    p.add_argument('--output', type=Path, default=Path(__file__).resolve().parent / 'shade_tables.h')
    a = p.parse_args()
    out = ['// Generated by make_shade_tables.py from OpenMoonRay sources: do not edit.',
           '// Apache-2.0, Copyright 2023-2024 DreamWorks Animation LLC. See MOONRAY_LICENSE.txt.',
           '#pragma once', '#include "sample_stream.h"',
           '#if defined(__CUDACC__)', '#define X2_TABLE static __device__ const', '#else',
           '#define X2_TABLE inline constexpr', '#endif',
           'namespace xpu2 { namespace interactive { namespace shade { namespace tables {']
    for path, names in TABLES:
        text = (a.source / SHADING / path).read_text(encoding='utf-8')
        for name in names:
            values = extract(text, name)
            out.append('X2_TABLE float %s[%d] = {' % (name, len(values)))
            for i in range(0, len(values), 12):
                out.append('    ' + ', '.join(v + 'f' if '.' in v or 'e' in v.lower() else v + '.0f'
                                              for v in values[i:i + 12]) + ',')
            out.append('};')
    out += ['}}}}', '#undef X2_TABLE', '']
    a.output.write_text('\n'.join(out), encoding='utf-8', newline='\n')
    print(a.output, sum(len(n) for _, n in TABLES), 'tables')


if __name__ == '__main__':
    main()
